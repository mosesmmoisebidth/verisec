const slug = (name: string) => name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");

/** The logo for a profile: by its site name, else by its address or the site it sits under (a.b.tumblr.com). */
export function siteIcon(site: string, url: string): string | null {
  const byName = SITE_ICON_FILES[slug(site)];
  if (byName) return `/site-icons/${byName}`;
  let host = "";
  try {
    host = new URL(url).hostname.toLowerCase().replace(/^www\./, "");
  } catch {
    return null;
  }
  for (let h = host; h.includes("."); h = h.slice(h.indexOf(".") + 1)) {
    const s = SITE_ICON_HOSTS[h];
    if (s && SITE_ICON_FILES[s]) return `/site-icons/${SITE_ICON_FILES[s]}`;
  }
  return null;
}
