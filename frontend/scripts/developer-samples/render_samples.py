"""Draw the engines' real output onto each sample and save one uniform-size image per sample,
plus a TS data file with the JSON the engines returned.

Boxes come from the detector run on the ORIGINAL upload (devsamples/<id>.detect.json); the MICR
read's own line box is drawn on top for cheques. Each photo is fitted whole (no crop) into an
800x500 frame over a blurred copy of itself; small specimen renders are never enlarged past 1.6x.
"""
import json, sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFilter, ImageOps, ImageEnhance

HERE = Path(__file__).parent
FE = Path(__file__).resolve().parents[2]
SAMPLES = FE / "public" / "finance" / "samples"
OUT = FE / "public" / "developers" / "samples"
OUT.mkdir(parents=True, exist_ok=True)
W, H = 800, 500
MAX_UP = 1.6
LIME, PINE, AMBER = (191, 235, 88), (14, 50, 40), (245, 166, 35)

ITEMS = [
    ("cheque-us", "Cheque", "US bank cheque", SAMPLES / "cheque-us.jpg", ["micr-line"]),
    ("cheque-cmc7", "Cheque", "Brazilian cheque (CMC-7)", SAMPLES / "cheque-cmc7.jpg", ["micr-line"]),
    ("cheque-ca", "Cheque", "Canadian certificate (E-13B)", SAMPLES / "cheque-ca.jpg", ["micr-line"]),
    ("card-mastercard", "Card", "Mastercard at a terminal", SAMPLES / "card-mastercard.jpg", ["number", "expiry"]),
    ("card-alfalah", "Card", "Visa specimen card", HERE / "card-alfalah.jpeg", ["number", "expiry"]),
    ("card-visa-classic", "Card", "Visa Classic specimen", HERE / "card-visa-classic.png", ["number", "expiry"]),
]
ENDPOINT = {"micr-line": "POST /v2/cheques/micr-line", "number": "POST /v2/cards/number", "expiry": "POST /v2/cards/expiry"}


def load(path: Path) -> Image.Image:
    im = ImageOps.exif_transpose(Image.open(path))
    if im.mode in ("RGBA", "LA", "P"):
        im = im.convert("RGBA")
        bg = Image.new("RGBA", im.size, (238, 241, 234, 255))
        im = Image.alpha_composite(bg, im)
    return im.convert("RGB")


def quad(pts, s, ox, oy):
    return [(ox + pts[i] * s, oy + pts[i + 1] * s) for i in range(0, 8, 2)]


data = []
for sid, kind, title, src, reads in ITEMS:
    det = json.load(open(HERE / "devsamples" / f"{sid}.detect.json"))
    im = load(src)
    if im.size != (det["width"], det["height"]):
        sys.exit(f"{sid}: image {im.size} != detector {det['width']}x{det['height']}")
    # backdrop: a plain-background render (all four corners alike) extends that colour to the frame;
    # a photo gets itself, covering the frame, blurred and slightly dimmed
    px = im.load()
    corners = [px[0, 0], px[im.width - 1, 0], px[0, im.height - 1], px[im.width - 1, im.height - 1]]
    spread = max(max(c[k] for c in corners) - min(c[k] for c in corners) for k in range(3))
    if spread <= 18:
        bd = Image.new("RGB", (W, H), tuple(sum(c[k] for c in corners) // 4 for k in range(3)))
    else:
        cover = max(W / im.width, H / im.height)
        bd = im.resize((round(im.width * cover), round(im.height * cover)), Image.LANCZOS)
        bd = bd.crop(((bd.width - W) // 2, (bd.height - H) // 2, (bd.width - W) // 2 + W, (bd.height - H) // 2 + H))
        bd = ImageEnhance.Brightness(bd.filter(ImageFilter.GaussianBlur(18))).enhance(0.82)
    # the photo itself: whole, centred, never enlarged past MAX_UP
    s = min(W / im.width, H / im.height, MAX_UP)
    fg = im.resize((round(im.width * s), round(im.height * s)), Image.LANCZOS)
    ox, oy = (W - fg.width) // 2, (H - fg.height) // 2
    canvas = bd.copy()
    canvas.paste(fg, (ox, oy))

    over = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    d = ImageDraw.Draw(over)
    for b in det["boxes"]:
        q = quad(b["box"], s, ox, oy)
        d.polygon(q, fill=LIME + (46,))
        d.line(q + [q[0]], fill=PINE + (235,), width=5, joint="curve")
        d.line(q + [q[0]], fill=LIME + (255,), width=3, joint="curve")
    reads_json = {}
    for r in reads:
        reads_json[r] = json.load(open(HERE / "devsamples" / f"{sid}.{r}.json"))
    line = reads_json.get("micr-line", {}).get("line")
    if line and line.get("box"):
        q = quad(line["box"], s, ox, oy)
        d.line(q + [q[0]], fill=PINE + (255,), width=7, joint="curve")
        d.line(q + [q[0]], fill=AMBER + (255,), width=4, joint="curve")
    canvas = Image.alpha_composite(canvas.convert("RGBA"), over).convert("RGB")
    canvas.save(OUT / f"{sid}.jpg", quality=86, optimize=True, progressive=True)

    data.append({
        "id": sid,
        "kind": kind,
        "title": title,
        "src": f"/developers/samples/{sid}.jpg",
        "regions": len(det["boxes"]),
        "reads": [{"endpoint": ENDPOINT[r], "json": reads_json[r]} for r in reads],
        "detected": {"width": det["width"], "height": det["height"], "boxes": det["boxes"]},
    })
    print(f"{sid}: {im.size} scale={s:.2f} boxes={len(det['boxes'])} micr_box={'yes' if line else 'no'}")

ts = (
    "/**\n * Developers page sample gallery: generated by render_samples.py from the engines' real output.\n"
    " * Each image is the sample with every detected text region drawn on it (and, on cheques, the MICR\n"
    " * line the read returned). `reads` are the exact API answers; `detected` is what was drawn.\n"
    " * Do not edit by hand: re-run the engines and the script.\n */\n\n"
    "export type DeveloperSample = {\n"
    "  id: string;\n"
    "  kind: \"Cheque\" | \"Card\";\n"
    "  title: string;\n"
    "  src: string;\n"
    "  regions: number;\n"
    "  reads: { endpoint: string; json: Record<string, unknown> }[];\n"
    "  detected: { width: number; height: number; boxes: { box: number[]; score: number }[] };\n"
    "};\n\n"
    "export const developerSamples: DeveloperSample[] = " + json.dumps(data, ensure_ascii=False, indent=2) + ";\n"
)
(FE / "src" / "config" / "developer-samples.ts").write_text(ts, encoding="utf-8")
print("wrote", OUT, "and src/config/developer-samples.ts")
